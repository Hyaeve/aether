import { test, expect } from '@playwright/test'

async function openVideo(page) {
  await page.route('**/api/**', route => {
    const path = new URL(route.request().url()).pathname
    const json = path === '/api/auth/status' ? { initialized: true, authenticated: true }
      : path === '/api/state' ? { username: 'video-controls', storages: [{ id: 'local', type: 'local', name: '视频', enabled: true, config: {} }], tasks: [], settings: {}, traffic: {}, cache: {} }
        : path === '/api/files' ? [{ id: '/video.mp4', name: 'video.mp4', url: '/stream/video-controls.mp4', size: 100 }] : {}
    return route.fulfill({ json })
  })
  await page.route('**/stream/video-controls.mp4', route => route.fulfill({ status: 404 }))
  await page.goto('/files')
  await page.getByRole('button', { name: 'video.mp4', exact: true }).dblclick()
  await expect(page.locator('.video-viewer')).toBeVisible()
}

test('episodes follow the current directory and buttons dim at both ends',async({page})=>{
  await openVideo(page)
  await page.getByRole('button',{name:'关闭视频预览',exact:true}).click()
  await page.route('**/api/files?**',route=>route.fulfill({json:[{id:'/one.mp4',name:'01.mp4',url:'/stream/video-controls.mp4'},{id:'/notes.txt',name:'notes.txt'},{id:'/two.mp4',name:'02.mp4',url:'/stream/video-controls.mp4'}]}))
  await page.reload()
  await page.getByRole('button',{name:'01.mp4',exact:true}).dblclick()
  await expect(page.getByRole('button',{name:'上一集',exact:true})).toBeDisabled()
  await expect(page.getByRole('button',{name:'下一集',exact:true})).toBeEnabled()
  await page.getByRole('button',{name:'下一集',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'02.mp4',exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'下一集',exact:true})).toBeDisabled()
  await expect(page.getByRole('button',{name:'上一集',exact:true})).toBeEnabled()
  await page.getByRole('button',{name:'上一集',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'01.mp4',exact:true})).toBeVisible()
})

test('outside clicks keep video open; native fullscreen toggles and X/Escape close', async ({ page }, info) => {
  await openVideo(page)
  const viewer = page.locator('.video-viewer'), video = viewer.locator('video')
  await page.mouse.click(2, 2)
  await expect(viewer).toBeVisible()
  await expect(viewer).toBeFocused()
  await expect(video).not.toHaveAttribute('controls')
  const source = await video.getAttribute('src')
  await page.getByRole('button', { name: '全屏', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出全屏', exact: true })).toHaveAttribute('aria-pressed', 'true')
  expect(await viewer.evaluate(el => document.fullscreenElement === el)).toBe(true)
  await expect(viewer.locator('.video-fullscreen .lucide-minimize-icon')).toBeVisible()
  await page.screenshot({ path: info.outputPath('video-native-fullscreen.png') })
  await page.getByRole('button', { name: '退出全屏', exact: true }).click()
  await expect(page.getByRole('button', { name: '全屏', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await expect(viewer).toBeVisible()
  expect(await page.evaluate(() => document.fullscreenElement)).toBeNull()
  await expect(video).toHaveAttribute('src', source)
  await page.getByRole('button', { name: '关闭视频预览', exact: true }).click()
  await expect(viewer).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'video.mp4', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'video.mp4', exact: true }).dblclick()
  await page.mouse.click(2, 2)
  await page.keyboard.press('Escape')
  await expect(viewer).toHaveCount(0)
  await page.getByRole('button', { name: 'video.mp4', exact: true }).dblclick()
  await page.getByRole('button', { name: '全屏', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出全屏', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('Escape')
  await expect(viewer).toBeVisible()
  await expect(page.getByRole('button', { name: '全屏', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(viewer).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => document.fullscreenElement === null)).toBe(true)
})

test('keyboard playback, volume, episode buttons and subtitle menu are available', async ({ page }) => {
  await openVideo(page)
  await page.route('**/api/files/video-subtitles?**', route => new URL(route.request().url()).searchParams.has('track') ? route.fulfill({ contentType:'text/vtt',body:'WEBVTT\n\n00:00:00.000 --> 00:00:02.000\n中文字幕\n\n' }) : route.fulfill({ json: { tracks: [{ index: 2, language: 'zh', title: '中文', supported: true }] } }))
  await expect(page.getByRole('button', { name: '上一集', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '下一集', exact: true })).toBeDisabled()
  await page.locator('.video-viewer').focus()
  await page.keyboard.press('Space')
  await page.keyboard.press('ArrowUp')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('ArrowLeft')
  await expect(page.getByText('网速 待定', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '音轨', exact: true }).click()
  await expect(page.getByRole('menu').last()).toBeVisible()
  await page.getByRole('button', { name: '字幕', exact: true }).hover()
  await expect(page.getByRole('menu', { name: '字幕选择' })).toBeVisible()
  await expect(page.getByRole('menuitemradio', { name: '中文' })).toBeVisible()
  await page.getByRole('menuitemradio', { name:'中文',exact:true }).click()
  await expect(page.locator('.video-viewer track')).toHaveAttribute('src',/^blob:/)
  await expect(page.getByRole('menuitemradio',{name:'中文',exact:true})).toHaveAttribute('aria-checked','true')
  await page.getByRole('menuitemradio',{name:'关闭字幕',exact:true}).click()
  await expect(page.locator('.video-viewer track')).toHaveCount(0)
  await page.mouse.move(2, 2)
  await expect(page.getByRole('menu', { name: '字幕选择' })).toHaveCount(0)
})

for (const viewport of [{ width: 1440, height: 900 }, { width: 390, height: 780 }]) {
  test(`matte volume and four-row subtitle menu stay inside video at ${viewport.width}px`,async({page},info)=>{
    await page.setViewportSize(viewport)
    await openVideo(page)
    await page.route('**/api/files/video-subtitles?**',r=>r.fulfill({json:{tracks:Array.from({length:7},(_,index)=>({index,title:`字幕 ${index+1}`,supported:true}))}}))
    const viewer=page.locator('.video-viewer'),volume=viewer.locator('.video-volume')
    const contained=async child=>{
      const a=await viewer.boundingBox(),b=await child.boundingBox()
      expect(b.x).toBeGreaterThanOrEqual(a.x);expect(b.y).toBeGreaterThanOrEqual(a.y)
      expect(b.x+b.width).toBeLessThanOrEqual(a.x+a.width+.5);expect(b.y+b.height).toBeLessThanOrEqual(a.y+a.height+.5)
    }
    for(const theme of ['light','dark']){
      await page.evaluate(t=>document.documentElement.dataset.theme=t,theme)
      await volume.getByRole('button').hover()
      const popup=volume.locator('.video-volume-popup'),slider=volume.getByRole('slider')
      await expect(popup).toHaveCSS('background-color','rgb(48, 59, 68)')
      await expect(popup).toHaveCSS('backdrop-filter','none')
      await contained(popup);await contained(slider)
      const b=await slider.boundingBox()
      await page.mouse.click(b.x+b.width/2,b.y+b.height*.7)
      await expect.poll(()=>viewer.locator('video').evaluate(el=>el.volume)).toBeGreaterThan(.2)
      await expect.poll(()=>viewer.locator('video').evaluate(el=>el.volume)).toBeLessThan(.4)
      await expect(popup.locator('small')).toHaveText(/^\d+$/)
      const number=await popup.locator('small').boundingBox();expect(number.y+number.height).toBeLessThan(b.y)
      await page.screenshot({path:info.outputPath(`video-volume-${theme}-${viewport.width}.png`)})
      await viewer.getByRole('button',{name:'字幕',exact:true}).hover()
      const menu=page.getByRole('menu',{name:'字幕选择'})
      await expect(menu.getByRole('menuitemradio')).toHaveCount(8)
      await expect(menu).toHaveCSS('scrollbar-width','none');await contained(menu)
      if(viewport.width===1440)await expect(menu).toHaveCSS('height','188px')
      await menu.hover();await page.mouse.wheel(0,600)
      await expect.poll(()=>menu.evaluate(el=>el.scrollTop)).toBeGreaterThan(0)
      await expect(menu.getByRole('menuitemradio',{name:'字幕 7',exact:true})).toBeInViewport()
      await page.screenshot({path:info.outputPath(`video-subtitles-${theme}-${viewport.width}.png`)})
    }
  })
  test(`fullscreen fallback fits ${viewport.width}px and restores without closing`, async ({ page }, info) => {
    await page.setViewportSize(viewport)
    await page.addInitScript(() => Object.defineProperty(document, 'fullscreenEnabled', { configurable: true, get: () => false }))
    await openVideo(page)
    const viewer = page.locator('.video-viewer')
    await page.getByRole('button', { name: '全屏', exact: true }).click()
    await expect(page.getByRole('button', { name: '退出全屏', exact: true })).toBeVisible()
    const bounds = await viewer.boundingBox()
    expect(bounds.x).toBeCloseTo(0, 0); expect(bounds.y).toBeCloseTo(0, 0)
    expect(bounds.width).toBeCloseTo(viewport.width, 0); expect(bounds.height).toBeCloseTo(viewport.height, 0)
    await page.screenshot({ path: info.outputPath('video-page-fullscreen.png') })
    await page.getByRole('button', { name: '退出全屏', exact: true }).click()
    await expect(page.getByRole('button', { name: '全屏', exact: true })).toBeVisible()
    await page.mouse.click(2, 2)
    await expect(viewer).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(viewer).toHaveCount(0)
  })
}
