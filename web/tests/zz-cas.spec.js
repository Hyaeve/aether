import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import path from 'node:path'

test('local CAS generation and persisted named directory navigation', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('my-aether-owner')
  await page.getByLabel('密码', { exact: true }).fill('a1')
  await page.getByRole('button', { name: '登录工作空间', exact: true }).click()
  await page.getByRole('link', { name: '任务管理', exact: true }).click()
  await page.getByRole('link', { name: 'CAS 任务', exact: true }).click()
  await page.getByRole('button', { name: '添加任务', exact: true }).click()
  await page.getByLabel('任务名称').fill('本地 CAS 哈希')
  await expect(page.getByRole('button', { name: '绑定存储', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '选择目录', exact: true })).toBeEnabled()
  await expect(page.getByRole('button', { name: '保存任务', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '选择目录', exact: true }).click()
  const sourceState = await (await page.request.get('/api/state')).json()
  const sources = sourceState.storages.filter(s => s.enabled)
  await expect(page.locator('.source-accounts button')).toHaveCount(sources.length)
  for (const source of sources) await expect(page.locator('.source-accounts')).toContainText(source.name)
  await page.keyboard.press('Escape')
  const inputBox = await page.getByLabel('任务名称').boundingBox()
  const selectBox = await page.getByRole('button', { name: '生成方式', exact: true }).boundingBox()
  expect(selectBox.height).toBe(inputBox.height)
  await expect(page.getByRole('dialog')).toHaveCSS('scrollbar-width', 'none')
  await expect(page.getByRole('button', { name: 'CAS 操作', exact: true })).toHaveCount(0)
  await page.getByLabel('生成目录', { exact: true }).fill('local-cas')
  await page.getByRole('button', { name: '选择目录', exact: true }).click()
  await page.locator('.source-accounts').getByRole('button', { name: /家庭影音库/ }).click()
  await page.getByRole('dialog', { name: '选择存储目录' }).getByRole('button', { name: 'Movies', exact: true }).click()
  await page.getByRole('button', { name: '选择当前目录', exact: true }).click()
  await expect(page.locator('.source-trigger')).toContainText('Movies')
  await expect(page.getByLabel('还原文件保留时间', { exact: true })).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('local-cas-form.png'), fullPage: true })
  await page.getByRole('button', { name: '保存任务', exact: true }).click()
  const row = page.locator('.task-row-card').filter({ hasText: '本地 CAS 哈希' })
  await row.getByRole('button', { name: '立即执行', exact: true }).click()
  await expect.poll(async () => {
    const state = await (await page.request.get('/api/state')).json()
    return state.tasks.find(t => t.name === '本地 CAS 哈希')?.status
  }).toBe('success')
  const output = readFileSync(path.join(process.env.AETHER_E2E_ROOT, 'data', 'strm', 'local-cas', 'Arrival.cas.strm'), 'utf8')
  const link = new URL(output.trim())
  const claim = JSON.parse(Buffer.from(link.pathname.replace('/stream/', ''), 'base64url').toString('utf8'))
  const info = claim.cas
  expect(info.sha256).toBe(createHash('sha256').update('test-video-content').digest('hex'))
  expect(info.provider || '').toBe('')
  expect(claim.s || '').toBe('')
  expect(claim.retentionHours || 0).toBe(0)
  expect(info.retentionHours || 0).toBe(0)
  expect(claim.redirect).toBe(true)
  expect(info.md5).toBe(createHash('md5').update('test-video-content').digest('hex'))
  expect(link.searchParams.get('sign')).toBeTruthy()
  await page.reload()
  await row.getByRole('button', {name:'任务操作 本地 CAS 哈希',exact:true}).click()
  await row.getByRole('button', { name: '编辑任务', exact: true }).click()
  await expect(page.locator('.source-trigger')).toContainText('Movies')
  await page.getByRole('button', { name: '选择目录', exact: true }).click()
  await expect(page.locator('.directory-crumbs [aria-current="location"]')).toHaveText('Movies')
  await page.getByRole('navigation', { name: '存储目录路径' }).getByRole('button', { name: '根目录', exact: true }).click()
  await expect(page.locator('.directory-crumbs [aria-current="location"]')).toHaveText('根目录')
})
