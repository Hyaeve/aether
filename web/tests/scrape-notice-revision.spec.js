test('scope tree defaults to all, excludes children and can clear/reinclude ranges',async({page},info)=>{
  await base(page)
  await page.route('**/api/strm-scrape/**',r=>{
    const url=new URL(r.request().url()),action=url.pathname.split('/').at(-1)
    if(action==='items')return r.fulfill({json:[{path:'Show/Season 1/1.strm',directories:['Show/Season 1'],title:'Show',kind:'tv'}]})
    if(action==='directories')return r.fulfill({json:{root:'/data/strm',directories:url.searchParams.get('path')==='Show'?['Show/Season 1','Show/Season 2']:['Show','Movies']}})
    return r.fulfill({json:{running:false}})
  })
  await page.goto('/tasks/scrape');await page.getByRole('button',{name:'筛选库目录'}).click()
  const dialog=page.getByRole('dialog',{name:'刮削范围'})
  await expect(dialog.getByRole('checkbox',{name:'全部目录',exact:true})).toBeChecked()
  await dialog.getByRole('button',{name:'展开 Show',exact:true}).click()
  await dialog.getByRole('checkbox',{name:'Show/Season 1',exact:true}).uncheck()
  await expect(dialog.getByRole('checkbox',{name:'Show/Season 2',exact:true})).toBeChecked()
  await dialog.getByRole('button',{name:'折叠 Show',exact:true}).click()
  await expect(dialog.getByRole('checkbox',{name:'Show/Season 1',exact:true})).toHaveCount(0)
  await dialog.getByRole('button',{name:'展开 Show',exact:true}).click()
  await expect(dialog.getByRole('checkbox',{name:'Show/Season 1',exact:true})).not.toBeChecked()
  await dialog.getByRole('checkbox',{name:'全部目录',exact:true}).check()
  await dialog.getByRole('checkbox',{name:'全部目录',exact:true}).uncheck()
  await expect(dialog.getByRole('checkbox',{name:'Movies',exact:true})).not.toBeChecked()
  await dialog.getByRole('checkbox',{name:'Show/Season 2',exact:true}).check()
  await expect(dialog.getByRole('checkbox',{name:'Show/Season 1',exact:true})).not.toBeChecked()
  await expect(dialog.getByRole('checkbox',{name:'Movies',exact:true})).not.toBeChecked()
  await page.screenshot({path:info.outputPath('scope-tree.png')})
  await dialog.getByRole('checkbox',{name:'全部目录',exact:true}).check()
  await dialog.getByRole('checkbox',{name:'全部目录',exact:true}).uncheck()
  await dialog.getByRole('button',{name:'确认范围',exact:true}).click()
  await expect(page.locator('.scrape-card')).toHaveCount(0)
})
