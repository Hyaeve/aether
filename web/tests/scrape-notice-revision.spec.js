  await expect(dock).toBeVisible();await page.keyboard.press('Escape');await expect(dock).toHaveCount(0)
  await cards.nth(0).getByRole('button',{name:'匹配 作品0',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'选择媒体匹配'})
  await expect(dialog.locator('.candidate-card')).toHaveCount(0)
  await expect(dialog).not.toContainText('没有找到候选')
