    const url=new URL(r.request().url()),action=url.pathname.split('/').at(-1)
    if(action==='items')return r.fulfill({json:items.map((i,n)=>n===0&&matched?{...i,poster:'/aether.svg',status:'ok',tmdb:123}:i)})
    if(action==='directories')return r.fulfill({json:{root:'/media/strm',directories:[]}})
    if(action==='status') {const previous=running;running=false;return r.fulfill({json:{running:false,taskId:'t',message:previous?'刮削完成':''}})}
    if(action==='settings')return r.fulfill({json:{writeMode:'missing'}})
    if(action==='candidates')return r.fulfill({json:[{id:123,title:'候选影片名称很长需要省略并显示完整信息',year:'2026',poster:'/aether.svg'},{id:456,title:'第二部',year:'2020',poster:'/aether.svg'}]})
